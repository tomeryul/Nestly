/** Fast prefix/substring search over the built-in catalogue. */
export function searchCatalog(query: string, limit = 8) {
  const q = query.trim();
  if (!q) return [];
  const starts: typeof PRODUCT_CATALOG = [];
  const contains: typeof PRODUCT_CATALOG = [];
  for (const p of PRODUCT_CATALOG) {
    if (p.name.startsWith(q)) starts.push(p);
    else if (p.name.includes(q)) contains.push(p);
    if (starts.length >= limit) break;
  }
  return [...starts, ...contains].slice(0, limit);
}
